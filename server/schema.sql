CREATE INDEX IF NOT EXISTS appointments_user_id_idx ON appointments(user_id);
CREATE INDEX IF NOT EXISTS appointments_scheduled_at_idx ON appointments(scheduled_at);
CREATE INDEX IF NOT EXISTS services_category_id_idx ON services(category_id);
CREATE INDEX IF NOT EXISTS orders_user_id_created_at_idx ON orders(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS order_items_service_id_idx ON order_items(service_id);
CREATE INDEX IF NOT EXISTS service_reviews_service_id_idx ON service_reviews(service_id, created_at DESC);
CREATE INDEX IF NOT EXISTS password_reset_requests_status_idx ON password_reset_requests(status, created_at DESC);

